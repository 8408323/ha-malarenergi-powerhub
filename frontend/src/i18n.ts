export type T = Dict;
const DICTS: Record<string, Dict> = { en, sv, nb, da, fi, is: is_ };
const LOCALES: Record<string, string> = { en: "en-GB", sv: "sv-SE", nb: "nb-NO", da: "da-DK", fi: "fi-FI", is: "is-IS" };
export const LANG_NAMES: Record<string, string> = { en: "English", sv: "Svenska", nb: "Norsk (bokmål)", da: "Dansk", fi: "Suomi", is: "Íslenska" };

// setting "auto" (or unset) follows HA: "nb-NO", "no", "nn" -> nb; "sv-SE" -> sv; unsupported -> en
export function pick(hassLang: string | undefined, setting?: string): { t: T; locale: string } {
  let code = setting && setting !== "auto" ? setting : String(hassLang ?? "en").toLowerCase().split(/[-_]/)[0];
  if (code === "no" || code === "nn") code = "nb";
  if (!DICTS[code]) code = "en";
  return { t: DICTS[code], locale: LOCALES[code] };
}
